    print("[RUNNING] Executing Extreme Docker Stress & Crash Test...")
    start_time = time.time()

    process = subprocess.Popen(
        docker_cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        encoding='utf-8',
        errors='replace',
        bufsize=1
    )

