import os
import sys
import subprocess
import time

PROJECT_DIR = os.path.dirname(os.path.abspath(__file__))
SRC_DIR = os.path.join(PROJECT_DIR, "src")
CONFIG_TCL = os.path.join(SRC_DIR, "config.tcl")

def setup_config_tcl(design_name="garuda_supreme_top", die_area="0 0 2000 2000"):
    """Creates custom OpenLane config.tcl for full local hardening and GDSII streaming."""
    tcl_content = f"""# Auto-generated by GARUDA Local Harden Script
# Architect: Anggit Prasetyo Mituhu

set ::env(DESIGN_NAME) "{design_name}"
set ::env(VERILOG_FILES) {{ /workspace/src/project.v }}
set ::env(CLOCK_PORT) "clk_sys"
set ::env(CLOCK_PERIOD) "2.0"
set ::env(FP_SIZING) "absolute"
set ::env(DIE_AREA) "{die_area}"
set ::env(CORE_AREA) "10 10 1990 1990"
set ::env(PL_TARGET_DENSITY) "0.55"
set ::env(VDD_NETS) {{ VDD_CORE VDD_MEM VDD_IO }}
set ::env(GND_NETS) {{ VSS_GND }}
set ::env(RUN_KLAYOUT) 1
set ::env(MAGIC_GENERATE_GDS) 1
set ::env(MAGIC_GENERATE_LEF) 1
set ::env(MAGIC_GENERATE_MAG) 1
set ::env(RUN_MAGIC) 1
set ::env(RUN_MAGIC_DRC) 1
set ::env(RUN_LVS) 1
"""
    with open(CONFIG_TCL, "w", encoding="utf-8") as f:
        f.write(tcl_content)
    print(f"[OK] Configuration written to {CONFIG_TCL}")

def run_docker_harden():
    """Runs full OpenLane Harden flow inside Docker container to generate GDSII and PNG visual renders."""
    docker_cmd = [
        "docker", "run", "--rm",
        "-v", f"{PROJECT_DIR}:/workspace",
        "goldenways/design-chip:v1.2",
        "bash", "-c",
        "flow_path=$(find /nix/store/ -name flow.tcl 2>/dev/null | grep bin/flow.tcl | head -n 1) && "
        "echo \"[INFO] Executing wrapper: $flow_path\" && "
        "$flow_path -design /workspace/src && "
        "echo \"[INFO] Generating GDSII layout images...\" && "
        "gds_file=$(find /workspace/src/runs/ -name \"*.gds\" 2>/dev/null | head -n 1) && "
        "if [ -f \"$gds_file\" ]; then "
        "  python3 /workspace/gds_to_image.py \"$gds_file\" /workspace/docs/images/;"
        "fi"
    ]
    print(f"[RUNNING] Executing Full OpenLane Harden Flow inside Docker container...")
    print(f"Command: {' '.join(docker_cmd)}\n")

    start_time = time.time()
    process = subprocess.Popen(
        docker_cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        encoding='utf-8',
        errors='replace',
        bufsize=1
    )

    while True:
        line = process.stdout.readline()
        if not line and process.poll() is not None:
            break
        if line:
            print(line, end='', flush=True)

    process.wait()
    elapsed = time.time() - start_time
    print(f"\n[DONE] Execution finished in {elapsed:.1f} seconds with exit code {process.returncode}.")

if __name__ == "__main__":
    print("=== GARUDA LOCAL OPENLANE HARDEN & GDSII GENERATOR v1.0 ===")
    print("Architect & Author: Anggit Prasetyo Mituhu\n")
    setup_config_tcl()
    run_docker_harden()
