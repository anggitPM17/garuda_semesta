import os
import sys
import subprocess
import time

PROJECT_DIR = os.path.dirname(os.path.abspath(__file__))
GPU_SRC_DIR = os.path.join(PROJECT_DIR, "gpu_src")
CONFIG_TCL = os.path.join(PROJECT_DIR, "src", "config.tcl")

def setup_config_tcl(design_name="garuda_gpu_top", die_area="0 0 25000 25000"):
    """Creates custom OpenLane config.tcl for GARUDA GPU 64-Core Ray-Tracing hardening."""
    tcl_content = f"""# Auto-generated by GARUDA GPU Local Harden Script
# Architect: Anggit Prasetyo Mituhu

set ::env(DESIGN_NAME) "{design_name}"
set ::env(VERILOG_FILES) {{ /workspace/gpu_src/garuda_gpu_top.v }}
set ::env(CLOCK_PORT) "clk_gpu"
set ::env(CLOCK_PERIOD) "2.0"
set ::env(FP_SIZING) "absolute"
set ::env(DIE_AREA) "{die_area}"
set ::env(CORE_AREA) "50 50 24950 24950"
set ::env(PL_TARGET_DENSITY) "0.65"
set ::env(VDD_NETS) {{ VDD_GPU VDD_MEM VDD_IO }}
set ::env(GND_NETS) {{ VSS_GND }}
set ::env(RUN_KLAYOUT) 0
set ::env(RUN_CROWBAR) 0
set ::env(SYNTH_ELABORATE_ONLY) 0
"""
    with open(CONFIG_TCL, "w", encoding="utf-8") as f:
        f.write(tcl_content)
    print(f"[OK] Configuration written to {CONFIG_TCL} (Target: {design_name})")

def run_docker_harden():
    """Runs OpenLane Harden flow inside Docker container to verify GARUDA GPU."""
    docker_cmd = [
        "docker", "run", "--rm",
        "-v", f"{PROJECT_DIR}:/workspace",
        "goldenways/design-chip:v1.2",
        "bash", "-c",
        "flow_path=$(find /nix/store/ -name flow.tcl 2>/dev/null | grep bin/flow.tcl | head -n 1) && echo \"[INFO] Executing wrapper: $flow_path\" && $flow_path -design /workspace/src"
    ]
    print(f"[RUNNING] Executing GARUDA GPU Docker OpenLane Synthesis & Verification Flow...")
    print(f"Command: {' '.join(docker_cmd)}\n")

    start_time = time.time()
    process = subprocess.Popen(
        docker_cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        encoding='utf-8',
        errors='replace',
        bufsize=1
    )

    while True:
        line = process.stdout.readline()
        if not line and process.poll() is not None:
            break
        if line:
            print(line, end='', flush=True)

    process.wait()
    elapsed = time.time() - start_time
    print(f"\n[DONE] GARUDA GPU Docker Verification finished in {elapsed:.1f}s with exit code {process.returncode}.")

if __name__ == "__main__":
    print("=== GARUDA GPU DOCKER HARDEN AUTOMATOR v1.0 ===")
    print("Architect & Author: Anggit Prasetyo Mituhu\n")
    setup_config_tcl()
    run_docker_harden()
