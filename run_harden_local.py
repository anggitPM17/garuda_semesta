import os
import sys
import subprocess
import time

PROJECT_DIR = os.path.dirname(os.path.abspath(__file__))
SRC_DIR = os.path.join(PROJECT_DIR, "src")
CONFIG_TCL = os.path.join(SRC_DIR, "config.tcl")

def setup_config_tcl(design_name="garuda_excalibur_top", die_area="0 0 15000 15000"):
    """Creates custom OpenLane config.tcl for local hardening."""
    tcl_content = f"""# Auto-generated by GARUDA Local Harden Script
# Architect: Anggit Prasetyo Mituhu

set ::env(DESIGN_NAME) "{design_name}"
set ::env(VERILOG_FILES) {{ /workspace/src/project.v }}
set ::env(CLOCK_PORT) "clk_sys"
set ::env(CLOCK_PERIOD) "2.0"
set ::env(FP_SIZING) "absolute"
set ::env(DIE_AREA) "{die_area}"
set ::env(CORE_AREA) "50 50 14950 14950"
set ::env(PL_TARGET_DENSITY) "0.65"
set ::env(VDD_NETS) {{ VDD_CORE VDD_MEM VDD_IO }}
set ::env(GND_NETS) {{ VSS_GND }}
set ::env(RUN_KLAYOUT) 0
set ::env(RUN_CROWBAR) 0
set ::env(SYNTH_ELABORATE_ONLY) 0
"""
    with open(CONFIG_TCL, "w", encoding="utf-8") as f:
        f.write(tcl_content)
    print(f"[OK] Configuration written to {CONFIG_TCL}")

def run_docker_harden():
    """Runs OpenLane Harden flow inside Docker container."""
    docker_cmd = [
        "docker", "run", "--rm",
        "-v", f"{PROJECT_DIR}:/workspace",
        "goldenways/design-chip:v1.2",
        "bash", "-c",
        "cd /workspace && openlane /workspace/src/config.tcl"
    ]
    print(f"[RUNNING] Executing OpenLane Harden Flow inside Docker container...")
    print(f"Command: {' '.join(docker_cmd)}")

    start_time = time.time()
    res = subprocess.run(docker_cmd, capture_output=True, text=True)
    elapsed = time.time() - start_time

    print(f"[DONE] Execution finished in {elapsed:.1f} seconds.")
    print("=== DOCKER OUTPUT STDOUT ===")
    print(res.stdout)
    if res.stderr:
        print("=== DOCKER OUTPUT STDERR ===")
        print(res.stderr)

if __name__ == "__main__":
    print("=== GARUDA LOCAL OPENLANE HARDEN AUTOMATOR v1.0 ===")
    print("Architect & Author: Anggit Prasetyo Mituhu\n")
    setup_config_tcl()
    run_docker_harden()
